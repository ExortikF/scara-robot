"""Карта регистров привода (руководство C30, гл. 5 + снятый дамп обмена).

Две независимые части:

1. **Параметры `P-0nn`** — документированы в руководстве, адресуются по правилу
   ``4xxxx = 40001 + nn``. Правило проверено на двух точках: ``40077 -> P-076``
   и ``40099 -> P-098``.
2. **Регистр команд `0x1011`** и его константы — сняты с шины, в руководстве не
   описаны. Значения "вперёд"/"назад" несимметричны, см. WARNING ниже.
"""

from __future__ import annotations

# --- Параметры P-0nn -------------------------------------------------------

PARAM_BASE = 40001
"""Modbus-адрес параметра P-000 в нотации 4xxxx."""


def param_addr(number: int, *, zero_based: bool = True) -> int:
    """Modbus-адрес параметра ``P-0nn``.

    ``zero_based=True`` возвращает адрес для PDU (то, что ждёт pymodbus):
    ``40001 + nn - 40001 == nn``. ``zero_based=False`` — «человеческий» 4xxxx.

    >>> param_addr(98)
    98
    >>> param_addr(98, zero_based=False)
    40099
    """
    if not 0 <= number <= 999:
        raise ValueError(f"номер параметра вне диапазона: P-{number:03d}")
    return number if zero_based else PARAM_BASE + number


# Параметры из руководства (гл. 4.3, 5.4.1). Номер = nn в P-0nn.
P_MOTOR_MODEL = 2          # P-002 код модели мотора
P_SOFTWARE_VERSION = 3     # P-003 версия ПО (только чтение)
P_CONTROL_MODE = 4         # P-004 режим управления, 0..8

P_GEAR_NUM_HIGH = 28       # P-028 числитель эл. редуктора, старшие 4 разряда
P_GEAR_NUM_LOW = 29        # P-029 числитель эл. редуктора, младшие 4 разряда
P_GEAR_DEN = 30            # P-030 знаменатель эл. редуктора, 1..32767

P_PULSE_INPUT_MODE = 35    # P-035 формат импульсов, 0=импульс+направление
P_PULSE_DIRECTION = 36     # P-036 инверсия направления счёта, 0..1
P_PULSE_LOGIC = 37         # P-037 логика/фронт входов, 0..12
P_PULSE_FILTER = 38        # P-038 фильтр импульса, 0..21
P_DIR_FILTER = 39          # P-039 фильтр направления, 0..15
P_SMOOTH_FILTER_MS = 40    # P-040 экспоненциальное сглаживание, 0..5000 мс

# Из снятого дампа, в руководстве не сверено:
