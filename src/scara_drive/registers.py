    ZSP = 4            # нулевая скорость
    COIN = 5           # ПОЗИЦИОНИРОВАНИЕ ЗАВЕРШЕНО — искомый признак «встал»
    ASP = 6            # скорость достигнута
    ATRQ = 7           # момент достигнут
