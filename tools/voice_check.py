"""Проверка голосовых команд на синтезированной речи.

Живой микрофон для проверки не годится: результат зависит от того, как
человек сказал, и повторить вчерашний замер нельзя. Здесь речь наговаривает
системный голос macOS, поэтому запись каждый раз одна и та же и числа
сравнимы между версиями.

Считаются две вещи, и они тянут в разные стороны:

* сколько команд УСЛЫШАНО — иначе настройка «ничего не принимать» была бы
  идеальной;
* сколько раз команда померещилась в обычной речи, где её не было.

Замер, ради которого это написано: прежний порядок разбора ловил 11 команд
из 11, но срабатывал ложно на ВСЕХ десяти обрывках посторонней речи — робот
трогался с места от разговора рядом. После правки ложное осталось одно.

    ./.venv-rs/bin/python tools/voice_check.py
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import subprocess
import sys
import tempfile
import wave
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from scara_drive.voice import COMMANDS, MODEL_DIR, VoiceCommands  # noqa: E402

#: Команды, сказанные по-разному: и словарным словом, и разговорным.
КОМАНДЫ = [
    ("стоп", "стоп"), ("стоп", "стой"), ("стоп", "хватит"),
    ("старт", "старт"), ("старт", "пуск"), ("старт", "поехали"),
    ("линия", "линия"), ("линия", "линию"),
    ("положение", "положение"), ("положение", "исходное"),
    ("положение", "домой"),
]

#: Обычная речь без единой команды. Ровно то, что звучит рядом с роботом.
БОЛТОВНЯ = [
    "сегодня хорошая погода мы поехали в магазин за продуктами",
    "надо посмотреть как этот механизм собран и что там с редуктором",
    "он говорит что всё нормально работает но я не уверен совершенно",
    "давай сначала проверим питание а потом уже будем смотреть на плату",
    "я думаю что здесь нужен другой подход к этой задаче",
    "смотри какая интересная штука получается если повернуть вот так",
    "ну в общем ничего страшного просто попробуем ещё раз",
    "мне кажется мы что-то упустили в самом начале работы",
    "позвони пожалуйста завтра утром часов в десять",
    "там на столе лежат инструменты возьми пожалуйста отвёртку",
]

ГОЛОС = "Milena"


def наговорить(текст: str, путь: Path) -> None:
    """Записать фразу в 16 кГц моно — как её слышит распознаватель."""
    сырое = путь.with_suffix(".aiff")
    subprocess.run(["say", "-v", ГОЛОС, "-o", str(сырое), текст], check=True)
    subprocess.run(["afconvert", "-f", "WAVE", "-d", "LEI16@16000", "-c", "1",
                    str(сырое), str(путь)], check=True)
    сырое.unlink()


def разобрать(модель, грамматика, путь: str, слушатель) -> tuple | None:
    """Прогнать запись через тот же разбор, что и живой микрофон."""
    import vosk

    распознаватель = vosk.KaldiRecognizer(модель, 16000, грамматика)
    распознаватель.SetWords(True)
    файл = wave.open(путь)
    разборы = []
    while True:
        кусок = файл.readframes(VoiceCommands.BLOCK)
        if not кусок:
            break
        if распознаватель.AcceptWaveform(кусок):
            разборы.append(json.loads(распознаватель.Result()))
    разборы.append(json.loads(распознаватель.FinalResult()))

    for разбор in разборы:
        текст = разбор.get("text", "")
        if not текст:
            continue
        команда = VoiceCommands.match(текст)
        if команда and слушатель._confident(разбор, команда):
            return команда, текст
    return None


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--подробно", action="store_true",
                   help="показать разбор каждой записи")
    args = p.parse_args()

    try:
        import vosk
    except ImportError:
        print("нет vosk — проверять нечем. "
              "Запускайте через ./.venv-rs/bin/python")
        return 0
    if not MODEL_DIR.is_dir():
        print(f"нет модели распознавания: {MODEL_DIR}")
        return 0

    vosk.SetLogLevel(-1)
    модель = vosk.Model(str(MODEL_DIR))
    словарь = sorted({w for ws in COMMANDS.values() for w in ws})
    грамматика = json.dumps(словарь + ["[unk]"], ensure_ascii=False)

    слушатель = object.__new__(VoiceCommands)
    слушатель.bias = 0.0
    слушатель.rejected = 0
    слушатель.last_confidence = 0.0
    слушатель.reject_reason = ""

    поймано = пропущено = ложных = 0
    with tempfile.TemporaryDirectory() as папка:
        print("команды:")
        for ожидалось, фраза in КОМАНДЫ:
            путь = Path(папка) / f"cmd_{len(glob.glob(папка + '/*.wav'))}.wav"
            наговорить(фраза, путь)
            итог = разобрать(модель, грамматика, str(путь), слушатель)
            верно = итог is not None and итог[0] == ожидалось
            поймано += верно
            пропущено += not верно
            if not верно or args.подробно:
                метка = "ок" if верно else "НЕ УСЛЫШАЛ"
                print(f"  {метка:11} «{фраза}» -> {итог or '—'}")

        print("\nпосторонняя речь:")
        for номер, фраза in enumerate(БОЛТОВНЯ):
            путь = Path(папка) / f"talk_{номер}.wav"
            наговорить(фраза, путь)
            итог = разобрать(модель, грамматика, str(путь), слушатель)
            ложных += итог is not None
            if итог or args.подробно:
                метка = "ПОМЕРЕЩИЛОСЬ" if итог else "молчит"
                print(f"  {метка:13} «{фраза[:40]}...» -> {итог or '—'}")

    print(f"\nуслышано команд:      {поймано}/{len(КОМАНДЫ)}"
          f"  (пропущено {пропущено})")
    print(f"ложных срабатываний:  {ложных}/{len(БОЛТОВНЯ)}")

    # Границы взяты по замеру на этих же записях сразу после правки:
    # 11 из 11 и одно ложное. Просадка ниже — повод разбираться, а не
    # молча жить дальше.
    плохо = поймано < len(КОМАНДЫ) - 1 or ложных > 2
    print("хуже, чем было — смотрите, что поменялось" if плохо
          else "в пределах замеренного")
    return 1 if плохо else 0


if __name__ == "__main__":
    raise SystemExit(main())
